# field signatures & the trace form  (Sec. 9, 10)
# ---------------------------------------------------------------------------

def signature_from_minpoly(coeffs):
    """(r1, r2) of Q(theta) from an irreducible minimal polynomial (highest-first):
    r1 = number of real roots, r2 = number of complex-conjugate pairs."""
    P = sp.Poly(coeffs, x)
    r1 = int(P.count_roots())
    r2 = (P.degree() - r1) // 2
    return (r1, r2)


def field_signature(gen_expr):
    """((r1, r2), degree) of Q(gen_expr) via its exact minimal polynomial."""
    P = sp.Poly(sp.minimal_polynomial(gen_expr, x), x)
    r1 = int(P.count_roots())
    r2 = (P.degree() - r1) // 2
    return (r1, r2), int(P.degree())


def power_sums(coeffs, K):
    """Newton's identities: power sums p_0..p_K of the roots of a monic integer
    polynomial (highest-first, leading coefficient 1). Exact rationals."""
    c = [sp.Rational(v) for v in coeffs]
    assert c[0] == 1, "power_sums needs a monic polynomial"
    n = len(c) - 1
    cs = c[1:]                                    # cs[i-1] = coeff of x^{n-i}
    p = [sp.Integer(n)]                           # p_0 = n
    for k in range(1, K + 1):
        if k <= n:
            acc = sum(cs[i - 1] * p[k - i] for i in range(1, k))
            p.append(-acc - k * cs[k - 1])
        else:
            acc = sum(cs[i - 1] * p[k - i] for i in range(1, n + 1))
            p.append(-acc)
    return p


def trace_form_signature(coeffs):
    """Signature (n_pos, n_neg) of the trace form Tr_{K/Q}(z^2) on Q(theta).

    Builds the exact-integer Gram matrix G_{ij} = Tr(theta^{i+j}) = p_{i+j} from
    Newton power sums, then counts positive / negative eigenvalues EXACTLY via
    Sturm root counting on its (integer) characteristic polynomial -- an exact
    inertia computation rather than a floating eigenvalue solve. (Prop. 9.1.)
    """
    n = sp.Poly(coeffs, x).degree()
    p = power_sums(coeffs, 2 * n - 2)
    G = sp.Matrix(n, n, lambda i, j: p[i + j])
    lam = sp.symbols("lam")
    chi = sp.Poly(G.charpoly(lam).as_expr(), lam)
    # multiplicity of the zero eigenvalue = number of trailing zero coefficients
    mult0 = 0
    for cc in reversed(chi.all_coeffs()):
        if cc == 0:
            mult0 += 1
        else:
            break
    pos = chi.count_roots(sp.Integer(0), None) - mult0     # roots in (0, +inf)
    neg = chi.count_roots(None, sp.Integer(0)) - mult0     # roots in (-inf, 0)
    return int(pos), int(neg)


# ---------------------------------------------------------------------------
# companions & self-action ad_M  (Sec. 10)
# ---------------------------------------------------------------------------

def companion(coeffs):
    """Companion matrix (float numpy) of a monic polynomial, highest-first."""
    P = sp.Poly(coeffs, x)
    assert P.LC() == 1
    c = [float(v) for v in P.all_coeffs()]        # [1, c1, ..., cn]
    n = P.degree()
    M = np.zeros((n, n))
    M[1:, :-1] = np.eye(n - 1)
    M[:, -1] = [-c[n - k] for k in range(n)]      # last column: -c_n,...,-c_1
    return M


def companion_int(coeffs):
    """Integer companion matrix as a sympy Matrix (for exact charpoly work)."""
    return sp.Matrix(companion(coeffs).astype(int).tolist())


def ad_operator(M):
    """Matrix of the self-action ad_M : X -> M X - X M on matrix space, via the
    Kronecker identity  ad_M = M (x) I - I (x) M^T  (Def. 10.1 / Lemma 10.2)."""
    n = M.shape[0]
    I = np.eye(n)
    return np.kron(M, I) - np.kron(I, M.T)


