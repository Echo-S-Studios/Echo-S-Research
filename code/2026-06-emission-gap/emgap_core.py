"""Shared computational core for the Emission-Gap producer scripts.

Source paper: papers/2026-06-emission-gap/emission_gap_paper.tex
    "The Emission-Gap Theorem: No Salem Number in the Spectral Image,
     and the Cost Floor It Forces" (AceTheDactyl / Echo S Studios).

This module is a clean, self-contained re-implementation of the paper's
computational primitives (roots, Mahler measure, trace-down R(x)=x^m T(x+1/x),
the Salem flip-straddle decision, field / trace-form signatures, companion
matrices, and the self-action ad_M).  It is written to be imported by the
PRODUCER scripts in this folder; it deliberately does NOT import from, and is
independent of, the verifier suite in tests/2026-06-emission-gap/.

Precision policy (matches the paper's "exact arithmetic" banner):
  * transcendental / root magnitudes: mpmath at >= 40 decimal places;
  * every structural Salem decision (palindromy, flip-straddle root counting,
    field / trace-form signatures) is exact via sympy factorisation and Sturm
    root counting -- no floating point crosses a decision branch.
"""
