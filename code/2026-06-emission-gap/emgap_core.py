SOURCE_PAPER = "papers/2026-06-emission-gap/emission_gap_paper.tex"
FOLDER = "2026-06-emission-gap"


def data_dir() -> str:
    """Absolute path of data/2026-06-emission-gap/, created if missing."""
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.abspath(os.path.join(here, "..", ".."))
    d = os.path.join(repo, "data", FOLDER)
    os.makedirs(d, exist_ok=True)
    return d


def write_csv(filename: str, fieldnames, rows, script: str) -> str:
    """Write rows (list of dicts) to a CSV with a provenance comment header."""
    path = os.path.join(data_dir(), filename)
    with open(path, "w", newline="", encoding="utf-8") as f:
        f.write(f"# source: {SOURCE_PAPER}; generated by: code/{FOLDER}/{script}\n")
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in rows:
            w.writerow(r)
    return path


def _json_default(o):
    """Coerce sympy / numpy / mpmath scalars to native JSON types."""
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, sp.Integer):
        return int(o)
    if isinstance(o, (sp.Rational, sp.Float, mp.mpf)):
        return float(o)
    return str(o)


def write_json(filename: str, payload: dict, script: str) -> str:
    """Write a JSON object carrying _source_paper / _generated_by provenance."""
    path = os.path.join(data_dir(), filename)
    out = {"_source_paper": SOURCE_PAPER, "_generated_by": f"code/{FOLDER}/{script}"}
    out.update(payload)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2, default=_json_default)
        f.write("\n")
    return path


def s(val, digits: int = 30) -> str:
    """Decimal string of an mpmath value to `digits` significant figures."""
    return mp.nstr(mp.mpf(val), digits, strip_zeros=False)


# ---------------------------------------------------------------------------
# roots / Mahler measure  (Sec. 1; Def. 2.3; Cor. 6.1)
# ---------------------------------------------------------------------------

def mp_roots(coeffs):
    """High-precision roots of a polynomial, coefficients highest-degree-first."""
    cc = [c if isinstance(c, mp.mpc) else mp.mpf(str(c)) for c in coeffs]
    return mp.polyroots(cc, maxsteps=2000, extraprec=400)


def mahler(coeffs) -> mp.mpf:
    """Mahler measure  M(p) = |a_n| * prod_i max(1, |alpha_i|)  (highest-first)."""
    cc = [mp.mpf(str(c)) for c in coeffs]
    lead = abs(cc[0])
    prod = mp.mpf(1)
    for r in mp.polyroots(cc, maxsteps=2000, extraprec=400):
        m = abs(r)
        if m > 1:
            prod *= m
    return lead * prod


def arg_degrees(z) -> float:
    """Argument of a complex number in degrees, in [0, 360)."""
    ang = mp.degrees(mp.atan2(z.imag, z.real))
    return float(ang % 360)


# ---------------------------------------------------------------------------
# sympy plumbing
# ---------------------------------------------------------------------------

def as_poly(obj, var=x) -> sp.Poly:
    if isinstance(obj, sp.Poly):
        return obj
    if isinstance(obj, (list, tuple)):
        return sp.Poly(list(obj), var)
    return sp.Poly(obj, var)


def is_palindromic(coeffs) -> bool:
    """Self-reciprocal (palindromic) integer coefficient list, highest-first."""
    c = [sp.nsimplify(v) for v in coeffs]
    return c == c[::-1]


# ---------------------------------------------------------------------------
# trace-down  R(x) = x^m T(x + 1/x)  and the Salem flip-straddle  (Sec. 8)
# ---------------------------------------------------------------------------

def trace_down(Rpoly) -> sp.Poly:
    """Trace-down polynomial T(t) of a monic self-reciprocal R of even degree 2m.

    Uses the Chebyshev-type recurrence  x^k + x^{-k} = c_k(t)  with
    c_0 = 2, c_1 = t, c_{k+1} = t c_k - c_{k-1}, so that R(x) = x^m T(x + 1/x).
    (Def. 8.1 / Lemma 8.2.)
    """
    R = as_poly(Rpoly)
    deg = R.degree()
    assert deg % 2 == 0, "trace-down requires even degree"
    m = deg // 2
    a = list(reversed(R.all_coeffs()))          # a[k] = coeff of x^k
    c = [sp.Integer(2), t]                       # c_0, c_1
    for k in range(1, m):
        c.append(sp.expand(t * c[k] - c[k - 1]))
    T = sp.sympify(a[m])
    for k in range(1, m + 1):
        T += a[m + k] * c[k]
    return sp.Poly(sp.expand(T), t)


def flip_straddle(Tpoly) -> bool:
    """Salem flip-straddle (Lemma 8.2): T totally real with exactly one root in
    (2, inf) and the remaining m-1 roots in (-2, 2)."""
    T = as_poly(Tpoly, t)
    m = T.degree()
    if T.eval(2) == 0 or T.eval(-2) == 0:        # a root on the flip => not Salem
        return False
    if T.count_roots() != m:                     # not totally real
        return False
    n_out = T.count_roots(sp.Integer(2), None)   # roots in [2, +inf]
    n_in = T.count_roots(sp.Integer(-2), sp.Integer(2))
    return n_out == 1 and n_in == m - 1


# ---------------------------------------------------------------------------
# Salem detection (the paper's exact guard: palindromy + flip-straddle)
# ---------------------------------------------------------------------------

def salem_factors(poly):
    """Irreducible integer factors of `poly` that are Salem polynomials, decided
    exactly via monic palindromy + trace-down flip-straddle (Thm. 8.3 guard)."""
    P = as_poly(poly)
    out = []
    for fac, _mult in sp.factor_list(P.as_expr(), x)[1]:
        Q = sp.Poly(fac, x)
        d = Q.degree()
        if d < 4 or d % 2:
            continue
        coeffs = Q.all_coeffs()
        if coeffs[0] == -1:                       # normalise sign
            coeffs = [-cc for cc in coeffs]
            Q = sp.Poly(coeffs, x)
        if coeffs[0] != 1:                         # Salem numbers are integers
            continue
        if not is_palindromic(coeffs):
            continue
        if flip_straddle(trace_down(Q)):
            out.append(Q)
    return out


def has_salem_factor(poly) -> bool:
    return len(salem_factors(poly)) > 0


def is_salem_numeric(coeffs, tol=1e-9) -> bool:
    """Numeric Salem test from root geometry: one root outside the unit disk,
    one inside, the rest on the circle, dominant root real > 1 (highest-first)."""
    deg = len(coeffs) - 1
    if deg < 4 or deg % 2:
        return False
    rts = np.roots([complex(c) for c in coeffs])
    mods = np.abs(rts)
    outside = int(np.sum(mods > 1 + tol))
    inside = int(np.sum(mods < 1 - tol))
    oncirc = int(np.sum(np.abs(mods - 1) <= tol))
    if outside != 1 or inside != 1 or oncirc < 2:
        return False
    beta = rts[int(np.argmax(mods))]
    return abs(beta.imag) <= tol and beta.real > 1


