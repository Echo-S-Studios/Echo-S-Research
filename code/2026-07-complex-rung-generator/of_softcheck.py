# ---------- exact torsion-group helpers (Q/Z, rn idiom) --------------------
def subgrp_order(gens):
    """order of the subgroup of Q/Z generated by the given Fractions."""
    fs = [Fraction(f) % 1 for f in gens]
    d = 1
    for f in fs:
        d = d * f.denominator // math.gcd(d, f.denominator)
    # subgroup of (1/d)Z/Z generated by {f} = (1/g)Z/Z where g = d / gcd(d, {d*f})
    nums = [ (f.numerator * (d // f.denominator)) % d for f in fs ]
    g = d
    for n in nums:
        g = math.gcd(g, n)
    g = math.gcd(g, d)
    return d // g if g else 1

def delta_and_anchor(angle_set):
    """relational group order m = |<differences>| and absolute anchor n = |<angles>|."""
    A = sorted(set(Fraction(a) % 1 for a in angle_set))
    diffs = {(a - b) % 1 for a in A for b in A}
    m = subgrp_order(diffs) if diffs else 1
    n = subgrp_order(set(A)) if A else 1
    return m, n

# ---------- exact integer-poly predicates ----------------------------------
def is_irreducible_monic(pe):
    P = Poly(pe, x)
    if P.LC() != 1 or P.degree() < 1:
        return False
    if P.eval(0) == 0:
        return False
    fl = factor_list(pe)[1]
    return len(fl) == 1 and fl[0][1] == 1

def all_real(pe):
    """exact Sturm test: does integer poly pe (in x) have only real roots?"""
    P = Poly(pe, x)
    if P.degree() == 0:
        return True
    Q = P.sqf_part()
    return Q.count_roots() == Q.degree()

def admissible_D(pe, dmax):
    """charge-admissible <=> some D>=1 with every root^D real (psi^D, exact, no
    CRootOf).  Return witnessing D (anchor | 2D), else None.  (rn RN-C idiom.)"""
    n = Poly(pe, x).degree()
    lim = min(dmax, 4 * n * n + 2)
    for D in range(1, lim + 1):
        TD = resultant(pe.subs(x, y), x - y ** D, y)
        if all_real(TD):
            return D
    return None

