def subgrp_order(gens):
    """order of the subgroup of Q/Z generated by the given Fractions."""
    G = {Fraction(0)}
    frontier = set(f % 1 for f in gens)
    while frontier:
        new = {(g + h) % 1 for g in (G | frontier) for h in frontier} | G | frontier
        if new == G:
            break
        frontier = new - G
        G = new
    return len(G)

