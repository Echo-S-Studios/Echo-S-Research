def companion(coeffs):
    """Companion matrix of the monic polynomial x^n + c_{n-1} x^{n-1} + ... + c_0
    given the low-to-high tail coefficients [c_0, ..., c_{n-1}].

    With this convention companion([-1, -1]) (i.e. x^2 - x - 1) is the golden
    keystone [[0, 1], [1, 1]].
    """
    n = len(coeffs)
    Cm = sp.zeros(n)
    for i in range(1, n):
        Cm[i, i - 1] = 1
    for i in range(n):
        Cm[i, n - 1] = -coeffs[i]
    return Cm


def ad_matrix(R):
    """4x4 matrix of the Lie self-action ad_R(X) = [R, X] = R X - X R on M_2(Q),
    expressed in the basis {E11, E12, E21, E22}.
    """
    basis = [sp.Matrix([[1, 0], [0, 0]]), sp.Matrix([[0, 1], [0, 0]]),
             sp.Matrix([[0, 0], [1, 0]]), sp.Matrix([[0, 0], [0, 1]])]
    cols = []
    for E in basis:
        adE = R * E - E * R
        cols.append([adE[0, 0], adE[0, 1], adE[1, 0], adE[1, 1]])
    return sp.Matrix(cols).T


def mahler_numpy(coeffs):
    """Mahler measure of a monic integer polynomial via numpy roots.
    coeffs are high-to-low (numpy convention), leading coefficient 1.
    """
    roots = np.roots(coeffs)
    M = 1.0
    for r in roots:
        if abs(r) > 1.0 + 1e-12:
            M *= abs(r)
    return M


def mahler_mpmath(coeffs, dps=45):
    """High-precision Mahler measure of a monic integer polynomial (mpmath).
    coeffs high-to-low; returns an mpmath real.
    """
    mp.mp.dps = dps
    roots = mp.polyroots(coeffs, maxsteps=400, extraprec=300)
    M = mp.mpf(1)
    for r in roots:
        if abs(r) > 1:
            M *= abs(r)
    return M.real


def fibonacci(n):
    """List [F_0, ..., F_n] with F_0 = 0, F_1 = 1."""
    F = [0, 1]
    while len(F) <= n:
        F.append(F[-1] + F[-2])
    return F[:n + 1]


def is_primitive(M, iters=40):
    """True iff some power of the non-negative matrix M (numpy) is strictly
    positive (Perron-Frobenius primitivity)."""
    P = M.copy()
    for _ in range(iters):
        if np.all(P > 0):
            return True
        P = P @ M
    return False


def poly_str(coeffs):
    """Render a monic integer polynomial from high-to-low coeff list, e.g.
    [1, -1, -1] -> 'x^2-x-1', [1, -7, 1] -> 'x^2-7x+1'."""
    n = len(coeffs) - 1
    terms = []
    for i, a in enumerate(coeffs):
        p = n - i
        if a == 0:
            continue
        sign = "+" if a > 0 else "-"
        mag = abs(a)
        if p == 0:
            body = f"{mag}"
        elif p == 1:
            body = f"{'' if mag == 1 else mag}x"
        else:
            body = f"{'' if mag == 1 else mag}x^{p}"
        terms.append(sign + body)
    out = "".join(terms)
    return out[1:] if out.startswith("+") else out


def exact(expr):
    """Human-readable exact form of a sympy expression for JSON storage."""
    return str(sp.simplify(expr))


def approx(expr, digits=15):
    """Float value of a sympy expression for JSON storage."""
    return float(sp.N(expr, digits + 3))
