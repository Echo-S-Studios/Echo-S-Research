# ---------------------------------------------------------------------------
# Provenance / paths
# ---------------------------------------------------------------------------

SHORT = "2026-06-lambda-2c"
TEX = "lambda_2c_paper.tex"
SOURCE_PAPER = f"papers/{SHORT}/{TEX}"


def _repo_root():
    here = os.path.dirname(os.path.abspath(__file__))          # code/2026-06-lambda-2c
    return os.path.dirname(os.path.dirname(here))               # repo root


def data_dir():
    d = os.path.join(_repo_root(), "data", SHORT)
    os.makedirs(d, exist_ok=True)
    return d


def _generated_by(script):
    return f"code/{SHORT}/{script}"


def write_csv(filename, header, rows, script):
    """Write a CSV with the mandated provenance comment on line 1."""
    path = os.path.join(data_dir(), filename)
    with open(path, "w", newline="", encoding="utf-8") as f:
        f.write(f"# source: {SOURCE_PAPER}; generated by: {_generated_by(script)}\n")
        w = csv.writer(f)
        w.writerow(header)
        for row in rows:
            w.writerow(row)
    return path


def write_json(filename, obj, script):
    """Write a JSON object with the mandated provenance fields injected first."""
    path = os.path.join(data_dir(), filename)
    out = {"_source_paper": SOURCE_PAPER, "_generated_by": _generated_by(script)}
    out.update(obj)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
    return path


