def companion(coeffs):
    """Companion matrix of a monic poly coeffs=[1,c_{n-1},...,c_1,c_0].

    Coefficients sit in the last column; charpoly equals the given poly and
    trace(C**k) = sum(root_i**k) = Tr_{K/Q}(theta**k) for a primitive theta.
    Standard textbook (second) companion form.
    """
    n = len(coeffs) - 1
    C = zeros(n)
    for i in range(1, n):
        C[i, i - 1] = 1
    for i in range(n):
        C[i, n - 1] = -coeffs[n - i]
    return C


def trace_form_powerbasis(min_coeffs):
    """Exact trace-form Gram G_{ij}=Tr(theta^{i-1}theta^{j-1}) in the power basis,
    built from the regular representation (companion) of theta -- so the Gram is
    reconstructed from power sums, never transcribed."""
    C = companion(min_coeffs)
    n = C.shape[0]
    powers = [eye(n)]
    for _ in range(2 * n):
        powers.append(powers[-1] * C)
    p = [powers[k].trace() for k in range(2 * n)]
    return Matrix(n, n, lambda i, j: p[i + j])


def projector(B, G):
    """Exact G-orthogonal projector P = B (B^T G B)^{-1} B^T G onto col(B)."""
    return B * (B.T * G * B).inv() * B.T * G


def regular_rep(coords, min_coeffs):
    """Regular representation rho(alpha) of alpha = sum_i coords[i] theta^i on
    K = Q[x]/(m_theta), i.e. sum_i coords[i] C(m_theta)^i."""
    C = companion(min_coeffs)
    n = C.shape[0]
    rho = zeros(n)
    Cpow = eye(n)
    for a in coords:
        rho += a * Cpow
        Cpow = Cpow * C
    return rho


def _monic(poly, x=X):
    """Monic normalisation of a Q[x] polynomial expression (0 stays 0)."""
    poly = sp.expand(poly)
    if poly == 0:
        return sp.Integer(0)
    P = sp.Poly(poly, x)
    return sp.expand(P.as_expr() / P.LC())


def monic_gcd(polys, x=X):
    """Monic gcd of a list of Q[x] polynomials."""
    g = sp.Integer(0)
    for p in polys:
        g = sp.gcd(g, sp.expand(p))
    return _monic(g, x)


def determinantal_divisors(M, x=X):
    """D_0..D_n where D_k = monic gcd of all k-by-k minors of M (D_0 = 1)."""
    n = M.shape[0]
    D = [sp.Integer(1)]
    for k in range(1, n + 1):
        minors = [M.extract(list(rows), list(cols)).det()
                  for rows in combinations(range(n), k)
                  for cols in combinations(range(n), k)]
        D.append(monic_gcd(minors, x))
    return D


def invariant_factors(A, x=X):
    """Invariant factors f_1|f_2|...|f_n of A (from xI-A), each monic, via
    determinantal divisors f_k = D_k / D_{k-1}.  f_n is the minimal polynomial;
    prod(f_k) is the characteristic polynomial."""
    n = A.shape[0]
    M = x * eye(n) - A
    D = determinantal_divisors(M, x)
    return [sp.expand(sp.cancel(D[k] / D[k - 1])) for k in range(1, n + 1)]


def largest_invariant_factor(A, x=X):
    """Largest invariant factor of xI-A = minimal polynomial of A (Thm 3.3)."""
    return invariant_factors(A, x)[-1]


def coords_to_minpoly(coords, min_coeffs, x=X):
    """The paper's seed-naming bridge (Thm 3.3 / Ex 3.5): the minimal polynomial
    of alpha = sum coords[i] theta^i is the largest invariant factor of
    xI - rho(alpha).  Returns (minpoly_expr, is_algebraic_integer)."""
    A = regular_rep(coords, min_coeffs)
    mp_expr = largest_invariant_factor(A, x)
    P = sp.Poly(mp_expr, x)
    is_alg_int = all(c.is_Integer for c in P.all_coeffs())
    return mp_expr, is_alg_int


def poly_coeffs(expr, x=X):
    """Coefficient list [leading,...,constant] as ints where integral else strings."""
    P = sp.Poly(sp.expand(expr), x)
    out = []
    for c in P.all_coeffs():
        out.append(int(c) if c.is_Integer else str(c))
    return out


def poly_str(expr):
    return str(sp.expand(expr))


def mat_to_strlist(M):
    """2-D list of string entries (exact rationals preserved as 'p/q')."""
    return [[str(M[i, j]) for j in range(M.shape[1])] for i in range(M.shape[0])]


def mahler_measure(coeffs, dps=40):
    """Exact-to-<10^-30 Mahler measure of a monic integer polynomial given by
    coeffs=[1,...,c0]: product of max(1,|root|).  Returned as an mpf.
    maxsteps/extraprec are raised so multiple-root polynomials still converge."""
    mp.mp.dps = dps
    roots = mp.polyroots([mp.mpf(c) for c in coeffs],
                         maxsteps=200, extraprec=4 * dps)
    M = mp.mpf(1)
    for r in roots:
        M *= max(mp.mpf(1), abs(r))
    return M


def phi_mpf(dps=40):
    """The golden ratio as an mpf at the given precision."""
    mp.mp.dps = dps
    return (1 + mp.sqrt(5)) / 2


