def data_dir():
    """Absolute path to this paper's data/ folder, resolved from __file__ so the
    producers write to the right place regardless of the current directory."""
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(os.path.dirname(here))  # code/<short>/ -> code -> repo
    d = os.path.join(repo, "data", _SHORT)
    os.makedirs(d, exist_ok=True)
    return d


def generated_by(script):
    return f"code/{_SHORT}/{script}"


def write_json(script, filename, payload):
    """Write JSON with provenance fields _source_paper and _generated_by first."""
    out = {"_source_paper": SOURCE_PAPER, "_generated_by": generated_by(script)}
    out.update(payload)
    path = os.path.join(data_dir(), filename)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
        f.write("\n")
    return path


def write_csv(script, filename, header, rows):
    """Write a CSV whose first line is the provenance comment the archive expects."""
    path = os.path.join(data_dir(), filename)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(f"# source: {SOURCE_PAPER}; generated by: {generated_by(script)}\n")
        f.write(",".join(str(h) for h in header) + "\n")
        for row in rows:
            f.write(",".join(str(v) for v in row) + "\n")
    return path


