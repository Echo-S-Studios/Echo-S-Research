def mat(a, b, c, d):
    """Holding X = a + b e1 + c e2 + d i  ->  its 2x2 real matrix
    [[a+c, b-d],[b+d, a-c]]."""
    return Matrix([[a + c, b - d], [b + d, a - c]])


def cl_coords(M):
    """Inverse iso: 2x2 matrix -> (a,b,c,d) Clifford coordinates."""
    a = (M[0, 0] + M[1, 1]) / 2
    c = (M[0, 0] - M[1, 1]) / 2
    b = (M[1, 0] + M[0, 1]) / 2
    d = (M[1, 0] - M[0, 1]) / 2
    return (a, b, c, d)


KEYSTONE_R = mat(Q(1, 2), 1, Q(-1, 2), 0)  # R = 1/2 + e1 - 1/2 e2, mat = [[0,1],[1,1]]


def return_operator(Xmat, R=KEYSTONE_R):
    """The phi-keystone return operator L(X) = R X + X R - X (eq Lop)."""
    return R * Xmat + Xmat * R - Xmat


def return_operator_matrix(R=KEYSTONE_R):
    """4x4 matrix of L over the ordered Clifford basis {1,e1,e2,i}."""
    basis = [mat(1, 0, 0, 0), mat(0, 1, 0, 0), mat(0, 0, 1, 0), mat(0, 0, 0, 1)]
    cols = [list(cl_coords(return_operator(B, R))) for B in basis]
    return Matrix(cols).T


# ---------------------------------------------------------------------------
# SHA-256 witness chain (eq chain)
# ---------------------------------------------------------------------------

def witness_digest(prev_hash, body):
    """SHA-256(prev_hash || canonical-json(body))[0:16], the tamper-evident
    witness link of eq (chain).  canonical = sorted keys, no whitespace."""
    import hashlib
    canonical = json.dumps(body, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256((prev_hash + canonical).encode()).hexdigest()[:16]
    return canonical, digest
